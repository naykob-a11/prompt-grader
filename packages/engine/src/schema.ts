export type ParamKey = (typeof PARAMS)[number]['key'];
export type Params = Record<ParamKey, number>;

export const PARAM_KEYS = PARAMS.map((p) => p.key) as ParamKey[];

export const DEFAULT_PARAMS = Object.fromEntries(PARAMS.map((p) => [p.key, p.default])) as Params;

/** Fills missing or non-finite values with the neutral value, then rounds into range. */
export function clamp(input: Readonly<Record<string, unknown>>): Params {
  const out = { ...DEFAULT_PARAMS };
  for (const p of PARAMS) {
    const v = Number(input[p.key] ?? p.default);
    if (Number.isFinite(v)) out[p.key] = Math.round(Math.min(p.max, Math.max(p.min, v))) + 0;
  }
  return out;
}

export const ParamsSchema = z.object(
  Object.fromEntries(PARAMS.map((p) => [p.key, z.number().int().min(p.min).max(p.max)])),
) as unknown as z.ZodType<Params>;

/** The shape of seed/parameter-schema.json. */
export function toSeedSchema() {
  return {
    version: 1,
    schemaVersion: SCHEMA_VERSION,
    groups: PARAM_GROUPS.map((g) => ({
      group: g.label.th,
      subtitle: g.subtitle,
      params: PARAMS.filter((p) => p.group === g.id).map((p) => ({
        key: p.key,
        label: p.label.th,
        min: p.min,
        max: p.max,
        default: p.default,
        ...(p.kind === 'hue' ? { kind: p.kind } : {}),
        since: p.since,
      })),
    })),
  };
}
